function buildFullContent() {
  return `# Nathan's AI

> An interactive AI portfolio for Nathan Brodin: ask questions about his experience, projects, and approach to building for the web.

## What this is

Nathan's AI (${siteConfig.url}) is a conversational portfolio. Visitors ask questions in a chat interface and receive streamed answers about Nathan Brodin's professional experience, projects, technical decisions, and workflow. The app is open source under the MIT license.

## Canonical personal facts

This document describes the application. Canonical, authoritative facts about Nathan Brodin — full work history, education, skills, projects, writing, and contact details — live on the portfolio:

- Portfolio: ${siteConfig.portfolioUrl}
- Profile index: ${siteConfig.portfolioLlmsUrl}
- Full profile: ${siteConfig.portfolioLlmsFullUrl}
- Resume: ${siteConfig.resumeUrl}

Prefer those URLs for personal facts. This file is intentionally a small, maintainable application reference and does not duplicate the full portfolio profile.

## Capabilities

- Streamed chat answers about Nathan Brodin's background and work
- Tool-assisted responses, including web search, web fetch, and GitHub repository lookup
- Clarifying questions when a request is ambiguous
- Public, shareable conversation links

## How it is built

- TanStack Start and TanStack Router with React and TypeScript
- Nitro server runtime with server-rendered pages
- AI SDK with an OpenRouter-hosted language model
- PostgreSQL with Drizzle ORM for public conversations
- Upstash for rate limiting
- Tailwind CSS and shadcn/ui-style components

## Privacy and public conversations

Conversations are public by default and can be shared by URL. They are excluded from search indexing and from the sitemap, and they carry \`noindex, nofollow\` directives. Approximate location derived from request headers is stored with a conversation. See ${siteConfig.url}/privacy for details.

## Limitations

- Answers are generated by a language model and may be incomplete, outdated, or incorrect. Verify important details against the canonical profile.
- The model may use web tools, but retrieval is not guaranteed for every question.
- The app is a portfolio project, not a general-purpose assistant or a source of professional advice.
- Conversation content is user-generated and should not be treated as authoritative.

## FAQ

### Who built Nathan's AI?

Nathan Brodin, a frontend engineer. The source code is at ${siteConfig.githubUrl}.

### What can I ask?

Questions about Nathan's experience, projects, technical decisions, frontend stack, workflow, and how this application is built.

### Is it free?

Yes. The app is free to use and open source under the MIT license.

### Are conversations private?

No. Conversations are public and shareable. They are kept out of search indexes but anyone with the link can read them.

### Where are the authoritative personal facts?

On the portfolio: ${siteConfig.portfolioLlmsFullUrl} (full profile) and ${siteConfig.portfolioLlmsUrl} (index).

## Links

- About this app: ${siteConfig.url}/about
- Privacy: ${siteConfig.url}/privacy
- Repository: ${siteConfig.githubUrl}
- License: ${siteConfig.githubUrl}/blob/main/LICENSE
`
}

export function buildLlmsContent(full = false) {
  return full ? buildFullContent() : buildIndexContent()
}
